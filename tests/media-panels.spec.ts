import { test, expect } from '@playwright/test';
import { fixtures } from './fixtures';

test('radar e vídeo priorizam mídia e mantêm controles e informações acessíveis', async ({ page }) => {
  test.setTimeout(90000);
  await fixtures(page); await page.setViewportSize({ width: 1440, height: 1000 });
  await page.context().grantPermissions(['geolocation']);
  await page.context().setGeolocation({ latitude: -23.4356, longitude: -46.4731, accuracy: 10 });
  await page.goto('/');
  const camera = page.locator('#airport-camera'), frame = page.locator('#airport-camera-frame');
  await expect(frame).toBeVisible();
  expect((await frame.boundingBox())!.height / (await camera.boundingBox())!.height).toBeGreaterThan(.8);
  await camera.locator('summary').click();
  await expect(page.locator('#airport-camera-note')).toBeVisible();
  await expect(page.locator('#airport-camera-link')).toBeVisible();
  await camera.locator('summary').click();
  await expect(page.locator('#airport-camera-note')).not.toBeVisible();
  await camera.screenshot({ path: 'test-results/media-video.png' });
  await page.getByRole('button', { name: 'Redimensionar câmera', exact: true }).focus();
  const before = (await frame.boundingBox())!.height;
  await page.keyboard.press('Shift+ArrowUp');
  expect((await frame.boundingBox())!.height).toBeGreaterThan(before + 30);
  const radar = page.getByRole('region', { name: 'Radar compacto perto de mim' });
  await radar.getByRole('button', { name: 'Ativar radar local' }).click();
  await expect(radar).toContainText('1 aeronave', { timeout: 15000 });
  const map = radar.locator('.weather-traffic-map');
  expect((await map.boundingBox())!.height / (await radar.boundingBox())!.height).toBeGreaterThan(.72);
  await expect(radar.getByRole('button', { name: 'Atualizar posição' })).toBeVisible();
  await expect(radar.getByRole('button', { name: 'Abrir completo' })).toBeVisible();
  await radar.screenshot({ path: 'test-results/media-radar.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await radar.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  await radar.screenshot({ path: 'test-results/media-radar-mobile.png' });
  await page.locator('#mobile-menu-toggle').click();
  await page.getByRole('button', { name: 'Câmera do aeroporto', exact: true }).click();
  await expect(frame).toBeVisible();
  expect((await frame.boundingBox())!.height / (await camera.boundingBox())!.height).toBeGreaterThan(.7);
  await camera.screenshot({ path: 'test-results/media-video-mobile.png' });
});
