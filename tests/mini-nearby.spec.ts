import { test, expect } from '@playwright/test';
import { fixtures } from './fixtures';

test('radar compacto só consulta posição ao ativar e transfere localização ao dashboard', async ({ page }) => {
  test.setTimeout(90000);
  await fixtures(page);
  await page.context().grantPermissions(['geolocation']);
  await page.context().setGeolocation({ latitude: -23.4356, longitude: -46.4731, accuracy: 10 });
  let requests = 0;
  page.on('request', r => { if(r.url().includes('/point/-23.43560/-46.47310/11')) requests++; });
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  const mini = page.getByRole('region', { name: 'Radar compacto perto de mim' });
  await expect(mini).toBeVisible();
  await expect(mini.locator('canvas')).toHaveCount(0); expect(requests).toBe(0);
  await mini.getByRole('button', { name: 'Ativar radar local' }).click();
  await expect(mini).toContainText('1 aeronave', { timeout: 15000 });
  await expect(mini.locator('.weather-traffic-map')).toHaveAttribute('data-rain', 'true');
  await page.screenshot({ path: 'test-results/mini-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(mini).toBeVisible();
  expect(await mini.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  await page.screenshot({ path: 'test-results/mini-mobile.png' });
  await mini.getByRole('button', { name: 'Recolher radar compacto' }).click();
  await expect(mini.locator('canvas')).toHaveCount(0);
  await mini.getByRole('button', { name: 'Expandir radar compacto' }).click();
  await mini.getByRole('button', { name: 'Abrir completo' }).click();
  const dashboard = page.getByRole('dialog', { name: 'Radar perto de mim', exact: true });
  await expect(dashboard.getByRole('button', { name: 'Atualizar minha localização' })).toBeVisible();
  await expect(dashboard.locator('.nearby-flights')).toContainText('TAM1234', { timeout: 15000 });
  await dashboard.getByRole('button', { name: 'Fechar radar perto de mim' }).click();
  await expect(mini).toBeVisible(); expect(errors).toEqual([]);
});

test('localização negada no radar compacto mantém ação para tentar novamente', async ({ page }) => {
  await fixtures(page);
  await page.addInitScript(() => Object.defineProperty(navigator.geolocation, 'getCurrentPosition', { value: (_ok: unknown, error: (e: { code: number }) => void) => error({ code: 1 }) }));
  await page.goto('/');
  const mini = page.getByRole('region', { name: 'Radar compacto perto de mim' });
  await mini.getByRole('button', { name: 'Ativar radar local' }).click();
  await expect(mini.getByRole('alert')).toContainText('Acesso à localização negado');
  await expect(mini.locator('canvas')).toHaveCount(0);
  await expect(mini.getByRole('button', { name: 'Ativar radar local' })).toBeEnabled();
});

test('radar abre à esquerda, move pelo título e teclado e permanece dentro da tela', async ({ page }) => {
  await fixtures(page);
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.goto('/');
  const mini = page.getByRole('region', { name: 'Radar compacto perto de mim' });
  const handle = mini.getByRole('button', { name: 'Mover radar compacto' });
  await expect(mini).toBeVisible();
  const initial = (await mini.boundingBox())!;
  expect(initial.x).toBe(16);
  const grip = (await handle.boundingBox())!;
  await page.mouse.move(grip.x + 40, grip.y + 15);
  await page.mouse.down();
  await page.mouse.move(grip.x + 280, grip.y + 95, { steps: 8 });
  await page.mouse.up();
  await expect.poll(async () => Math.round((await mini.boundingBox())!.x)).toBe(256);
  await handle.focus();
  await page.keyboard.press('ArrowRight');
  expect(Math.round((await mini.boundingBox())!.x)).toBe(272);
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(async () => { const rect = (await mini.boundingBox())!; return rect.x + rect.width; }).toBeLessThanOrEqual(378);
  await page.keyboard.press('Home');
  expect(Math.round((await mini.boundingBox())!.x)).toBe(12);
  await expect(handle).toHaveCSS('touch-action', 'none');
  await expect(mini.getByRole('button', { name: 'Ativar radar local' })).toBeVisible();
});

test('redimensionar radar amplia o mapa e mantém tamanho ao recolher', async ({ page }) => {
  test.setTimeout(60000);
  await fixtures(page); await page.context().grantPermissions(['geolocation']);
  await page.context().setGeolocation({ latitude: -23.4356, longitude: -46.4731, accuracy: 10 });
  await page.setViewportSize({ width: 1440, height: 1000 }); await page.goto('/');
  const panel = page.getByRole('region', { name: 'Radar compacto perto de mim' });
  await panel.getByRole('button', { name: 'Ativar radar local' }).click();
  const handle = panel.getByRole('button', { name: 'Redimensionar radar', exact: true });
  await expect(handle).toBeVisible();
  const before = (await panel.boundingBox())!, map = panel.locator('.weather-traffic-map'), mapBefore = (await map.boundingBox())!;
  const grip = (await handle.boundingBox())!;
  await page.mouse.move(grip.x+12, grip.y+12); await page.mouse.down(); await page.mouse.move(grip.x+92, grip.y+72, { steps: 8 }); await page.mouse.up();
  await expect.poll(async () => Math.round((await panel.boundingBox())!.width)).toBe(Math.round(before.width)+80);
  await expect.poll(async () => Math.round((await map.boundingBox())!.height)).toBe(Math.round(mapBefore.height)+60);
  await panel.getByRole('button', { name: 'Recolher radar compacto' }).click();
  await panel.getByRole('button', { name: 'Expandir radar compacto' }).click();
  expect(Math.round((await map.boundingBox())!.height)).toBe(Math.round(mapBefore.height)+60);
  await handle.focus(); await page.keyboard.press('ArrowDown');
  expect(Math.round((await map.boundingBox())!.height)).toBe(Math.round(mapBefore.height)+76);
  await panel.screenshot({ path: 'test-results/radar-resized.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  expect((await panel.boundingBox())!.width).toBeLessThanOrEqual(366);
  await handle.focus(); await page.keyboard.press('Home');
  expect(Math.round((await panel.boundingBox())!.width)).toBe(256);
});
